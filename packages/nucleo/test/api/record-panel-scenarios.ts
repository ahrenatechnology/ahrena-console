// Records the panel's answer in each simulator scenario (P1 to P7, P9, P12 and P13) for the plugin's
// tests, which run with no network or disk. Fixed time (T0), simulator data. In P9 it also records
// the decision list of each scope, which the panel asks for with `?decisions=<scope>`.
//   node test/api/record-panel-scenarios.ts > ../../plugins/ahrena-console/tests/scenarios.ts
//
// The body is the one of the new route, `GET /api/panel/<session>` (#173 phase 2b, #187): English
// keys and values, exactly what the mod reads since 0.0.31.
import { openSqliteStorage } from '../../src/adapters/sqlite/sqlite-storage.ts';
import { Contas, ESCOPOS_DAS_DECISOES, MontadorDoPainel, TrabalhoPorBranch } from '../../src/api/index.ts';
import { SqliteDecisionStore } from '../../src/decisoes/sqlite.ts';
import { CENARIOS_DO_PAINEL, FonteDeTrabalhoDoSimulador, SESSAO_DO_PAINEL, semearCenariosDoPainel, semearDecisoesDoPainel } from '../../src/simulador/painel.ts';
import { T0 } from '../fixtures.ts';

const NOW = Date.parse(T0);
const panels: Record<string, unknown> = {};
const lists: Record<string, unknown> = {};
for (const name of CENARIOS_DO_PAINEL) {
  const storage = openSqliteStorage({ path: ':memory:' });
  const decisions = new SqliteDecisionStore(storage.db);
  await semearCenariosDoPainel(storage, name, NOW);
  await semearDecisoesDoPainel(decisions, name, NOW);
  const work = new TrabalhoPorBranch({ fonte: new FonteDeTrabalhoDoSimulador(), git: FonteDeTrabalhoDoSimulador.git, agora: () => NOW });
  const builder = new MontadorDoPainel({
    storage, contas: new Contas({ storage, arquivo: null }), desktop: null, trabalho: work, decisoes: decisions, agora: () => NOW, apelido: () => SESSAO_DO_PAINEL,
  });
  const request = { sessionId: 'sessao-teste', modelo: 'claude-sonnet-5-5', cwd: '/simulacao/cli-de-notas' };
  await builder.montar(request);
  await work.esperar();
  panels[name] = await builder.montar(request);
  if (name === 'p9') {
    for (const scope of ESCOPOS_DAS_DECISOES) lists[scope] = (await builder.montar({ ...request, decisoes: scope })).decisions!.list!;
  }
  await storage.close();
}
const names = CENARIOS_DO_PAINEL.map((c) => `'${c}'`).join(' | ');
process.stdout.write(
  `// Generated by packages/nucleo/test/api/record-panel-scenarios.ts: the answer of /api/panel in each\n` +
    `// simulator scenario (P1 to P7, P9, P12 and P13), at the fixed time NOW, and the P9 decision lists by scope.\n` +
    `// Do not edit: run the script again.\n` +
    `import type { DecisionList, DecisionScope, Panel } from '../types'\n\n` +
    `export const NOW = ${NOW}\n\n` +
    `export const SCENARIOS: Record<${names}, Panel> = ${JSON.stringify(panels, null, 2)}\n\n` +
    `export const P9_LISTS: Record<DecisionScope, DecisionList> = ${JSON.stringify(lists, null, 2)}\n`,
);
